import fs,{constants as F} from 'node:fs/promises';
import path from 'node:path';
import {spawn} from 'node:child_process';
import type {FileHandle} from 'node:fs/promises';
import type {Component,ComponentContext} from '../components/registry.js';
import {FoundationError} from '../policy/programme.js';
import {contentDigest,openWorkspace,readContained,relativePath,strictObject} from './names.js';
const GENERATED_PATHS=['AGENTS.md','CLAUDE.md','CODEMAP.md','.codify/agent-context.md','.hyperfide/context/agent-context.md'];
const GENERATORS=Object.freeze({
 spec:['spec','render'],agent_context:['agentmd','--write'],codemap:['codemap']
});
function fail(code:string,message:string):never{throw new FoundationError(code,message);}
function owned(file:string,bytes:Buffer):boolean{
 const body=bytes.toString('utf8');
 if(file==='AGENTS.md'||file==='CLAUDE.md')return body.includes('GENERATED by cg spec render')||body.includes('GENERATED by hyperfide spec render');
 if(file.endsWith('agent-context.md'))return /<!-- (?:codify|hyperfide)-owned: graph-agent-context v1 -->/.test(body);
 return /^<!-- (?:codify|hyperfide)-owned: codemap v1/.test(body);
}
async function inventory(root:FileHandle):Promise<unknown[]>{
 const result=[];
 for(const file of GENERATED_PATHS){
  const data=await readContained(root,file);
  if(data)result.push({path:file,digest:contentDigest(data.bytes),size_bytes:String(data.bytes.length),owner:owned(file,data.bytes)?'generator':'user'});
 }
 return result;
}
async function execute(binary:FileHandle,root:FileHandle,args:readonly string[],context:ComponentContext):Promise<{exit_code:number;stdout:Buffer;stderr:Buffer}>{
 if(context.signal.aborted)fail('GENERATION_CANCELLED','Generation was cancelled');
 return new Promise((resolve,reject)=>{
  const child=spawn('/proc/'+process.pid+'/fd/'+binary.fd,[...args],{
   cwd:'/proc/'+process.pid+'/fd/'+root.fd,env:{...context.env,HYPERFIDE_GENERATION_ROOT:'/proc/'+process.pid+'/fd/'+root.fd},detached:true,stdio:['ignore','pipe','pipe']});
  let total=0,killed=false;const stdout:Buffer[]=[],stderr:Buffer[]=[];
  const stop=()=>{killed=true;if(child.pid)try{process.kill(-child.pid,'SIGKILL');}catch{/* Exit can race cancellation. */}};
  const abort=()=>stop();context.signal.addEventListener('abort',abort,{once:true});
  const timer=setTimeout(stop,60000);
  const collect=(chunks:Buffer[])=>(data:Buffer)=>{total+=data.length;if(total>4194304)stop();else chunks.push(data);};
  child.stdout.on('data',collect(stdout));child.stderr.on('data',collect(stderr));
  child.once('error',()=>{clearTimeout(timer);context.signal.removeEventListener('abort',abort);reject(new FoundationError('GENERATION_UNAVAILABLE','Pinned executable could not start'));});
  child.once('close',(code)=>{
   clearTimeout(timer);context.signal.removeEventListener('abort',abort);
   if(killed)reject(new FoundationError('GENERATION_CANCELLED','Generation exceeded its execution budget or was cancelled'));
   else resolve({exit_code:code??1,stdout:Buffer.concat(stdout),stderr:Buffer.concat(stderr)});
  });
 });
}
async function executable(context:ComponentContext):Promise<FileHandle>{
 const filename=context.env.HF_MIGRATION_BINARY,pin=context.env.HF_MIGRATION_BINARY_SHA256;
 if(!filename||!path.isAbsolute(filename)||!pin||!/^sha256:[a-f0-9]{64}$/.test(pin))
  fail('GENERATOR_IDENTITY_REQUIRED','A trusted absolute executable and SHA-256 pin are required');
 const handle=await fs.open(filename,F.O_RDONLY|F.O_NOFOLLOW|F.O_NONBLOCK);
 try{
  const info=await handle.stat();if(!info.isFile()||info.size>536870912||!(info.mode&0o111))fail('GENERATOR_IDENTITY_INVALID','Executable is not a bounded ordinary executable');
  if(contentDigest(await handle.readFile())!==pin)fail('GENERATOR_IDENTITY_INVALID','Executable content differs from its trusted pin');
  return handle;
 }catch(e){await handle.close();throw e;}
}
export function createComponent(context:ComponentContext):Component{
 return {apiVersion:1,actions:{
  'migration.generated.inspect':async(value:unknown)=>{
   const input=strictObject(value,['workspace']),root=await openWorkspace(context,input.workspace);
   try{return {files:await inventory(root),user_owned_files_preserved:true};}finally{await root.close();}
  },
  'migration.generated.run':async(value:unknown)=>{
   const input=strictObject(value,['workspace','generators']);
   if(context.env.HF_MIGRATION_PLACEMENT!=='remote')fail('REMOTE_EXECUTION_REQUIRED','Guidance generation must execute in qualified remote capacity');
   if(!Array.isArray(input.generators)||!input.generators.length||input.generators.length>3||
    input.generators.some(v=>typeof v!=='string'||!Object.hasOwn(GENERATORS,v))||new Set(input.generators).size!==input.generators.length)
    fail('INVALID_REQUEST','Expected unique supported generators');
   const root=await openWorkspace(context,input.workspace);let binary:FileHandle|undefined;
   try{
    const before=await inventory(root) as {path:string;owner:string}[];
    const wanted=new Set<string>();
    for(const name of input.generators as string[]){
     if(name==='spec'){wanted.add('AGENTS.md');wanted.add('CLAUDE.md');}
     if(name==='agent_context'){wanted.add('.codify/agent-context.md');wanted.add('.hyperfide/context/agent-context.md');}
     if(name==='codemap')wanted.add('CODEMAP.md');
    }
    if(before.some(f=>wanted.has(f.path)&&f.owner!=='generator'))fail('GENERATED_FILE_CONFLICT','A selected output contains user-owned text; no generator was started');
    binary=await executable(context);
    const version=await execute(binary,root,['--version'],context);
    if(version.exit_code||version.stdout.toString('utf8').trim()!=='2.0.0-dev')fail('GENERATOR_VERSION_UNSUPPORTED','The pinned executable has an unsupported product version');
    for(const key of ['agent_context','spec'] as const)if((input.generators as string[]).includes(key)){
     const configured=await execute(binary,root,['config','get',key==='spec'?'paths.spec':'paths.context'],context);
     if(configured.exit_code)fail('GENERATION_FAILED','Configured generator paths could not be resolved');
     const directory=relativePath(configured.stdout.toString('utf8').trim());
     if(key==='spec'){
      if(!await readContained(root,directory+'/workflow.kvx'))fail('GENERATION_WORKFLOW_REQUIRED','A contained workflow is required; ancestor workflows are excluded');
     }else{
      const file=directory+'/agent-context.md',existing=await readContained(root,file);
      if(existing&&!owned(file,existing.bytes))fail('GENERATED_FILE_CONFLICT','Configured context contains user-owned text');
     }
    }
    const operations=[];
    for(const name of input.generators as (keyof typeof GENERATORS)[]){
     const result=await execute(binary,root,GENERATORS[name],context);
     if(result.exit_code)fail('GENERATION_FAILED','The '+name+' generator failed; prior backups and provenance remain intact');
     operations.push({generator:name,exit_code:0,stdout_digest:contentDigest(result.stdout),stderr_digest:contentDigest(result.stderr)});
    }
    return {operations,files:await inventory(root),user_owned_files_preserved:true,history_rewritten:false};
   }catch(e){
    if(e instanceof FoundationError)throw e;
    fail('GENERATION_FILESYSTEM_ERROR','Contained guidance generation failed');
   }finally{await binary?.close();await root.close();}
  }
 }};
}
