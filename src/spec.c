/* ---------------- little helpers ---------------- */

/* kvx_str but never NULL (Go's Str returns "") — always malloc'd */
static char *S(const Kvx *k, const char *sec, const char *key) {
    char *v = kvx_str(k, sec, key);
    return v ? v : xstrdup("");
}

static bool raw_is_list(const Kvx *k, const char *sec, const char *key) {
    const char *r = kvx_raw(k, sec, key);
    if (!r) return false;
    size_t n = strlen(r);
    return n >= 2 && r[0] == '[' && r[n - 1] == ']';
}

static int count_dots(const char *s) {
    int n = 0;
    for (; *s; s++) if (*s == '.') n++;
    return n;
}

/* superseded is terminal: the task is closed without qualifying, its work
 * owned by superseded_by. Closed for every count, never done, never next. */
static bool status_superseded(const char *status) {
    return strcmp(status, "superseded") == 0;
}

/* blocked is the waiting state (D4): an in_progress task whose attempt
 * raised a blocking Ask, named in blocked_ask. Not done, not next, not
 * eligible for dependants; only the Ask's answer returns it to
 * in_progress. The documentation stage's "blocked" is a different thing (a
 * failed docs closure) and is never a task status. */
static bool status_blocked(const char *status) {
    return strcmp(status, "blocked") == 0;
}

static const char *checkbox(const char *status) {
    if (strcmp(status, "done") == 0) return "[x]";
    if (strcmp(status, "in_progress") == 0) return "[-]";
    if (status_blocked(status)) return "[?]";
    if (status_superseded(status)) return "[~]";
    return "[ ]";
}

/* Go UintOr: whole value must parse as unsigned decimal, else fallback */
static unsigned long uint_or(const Kvx *k, const char *sec, const char *key,
                             unsigned long dflt) {
    char *v = kvx_str(k, sec, key);
    if (!v || !v[0]) { free(v); return dflt; }
    for (char *p = v; *p; p++)
        if (!isdigit((unsigned char)*p)) { free(v); return dflt; }
    unsigned long n = strtoul(v, NULL, 10);
    free(v);
    return n;
}

/* iterate entries of a section (file order), keys filtered by prefix */
#define FOR_KV(k, secname, prefix, idx) \
    for (int idx = 0; idx < (k)->n; idx++) \
        if (strcmp((k)->v[idx].section, (secname)) == 0 && \
            strncmp((k)->v[idx].key, (prefix), strlen(prefix)) == 0)

static char *entry_val(const Kvx *k, int i) {           /* interpolated */
    return S(k, k->v[i].section, k->v[i].key);
}

static int spec_find_root(char *out, size_t cap) {
    return config_find_spec_root(NULL, out, cap);
}

/* read include file relative to feature dir; TrimRight('\n'); NULL on error */
static char *read_include(const char *fdir, const char *rel) {
    char path[4600];
    snprintf(path, sizeof path, "%s/%s", fdir, rel);
    size_t len = 0;
    char *body = read_entire_file(path, &len);
    if (!body) return NULL;
    while (len && body[len - 1] == '\n') body[--len] = 0;
    return body;
}

/* ---------------- idempotent writer (Go writer{}) ---------------- */
typedef struct {
    bool check, quiet;
    int written, unchanged, stale;
} Writer;

static int writer_write_owned(Writer *w, const char *path, const char *content) {
    size_t nlen = strlen(content), olen = 0;
    char *old = read_entire_file(path, &olen);
    if (old && olen == nlen && memcmp(old, content, nlen) == 0) {
        free(old);
        w->unchanged++;
        return 0;
    }
    bool legacy_owned=old&&strstr(old,"<!-- GENERATED by ")!=NULL;
    free(old);
    if (w->check) {
        w->stale++;
        if (!w->quiet) fprintf(stderr, "stale: %s\n", path);
        return 0;
    }
    if (hyperfide_owned_write(path, content, nlen, "generated-spec v1", legacy_owned) != 0) {
        fprintf(stderr, "hyperfide spec: write %s failed\n", path);
        return -1;
    }
    w->written++;
    if (!w->quiet) fprintf(stderr, "wrote: %s\n", path);
    return 0;
}

static int writer_write(Writer *w,const char *path,const char *content) {
    StrBuf marked;sb_init(&marked);
    sb_puts(&marked,"<!-- hyperfide-owned: generated-spec v1 -->\n");
    sb_puts(&marked,content);
    int rc=writer_write_owned(w,path,marked.p);sb_free(&marked);return rc;
}

