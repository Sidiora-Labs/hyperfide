/*
 * cg spec — C port of ion-agent's spec/specgen plus a task engine.
 *
 *   cg spec render [--check]   regenerate IDE pointer files + markdown mirror
 *                              from spec KVX files (byte-compatible with specgen)
 *   cg spec [status]           task board for the active feature
 *   cg spec next               lowest-wave eligible task, with its ACs
 *   cg spec start <id>         mark in_progress (one at a time), refresh mirror
 *   cg spec implemented <id>   graph-check source work, mark qualification pending
 *   cg spec done <id>          verify_cmd gate, mark done, refresh mirror
 *
 * The kvx files stay the single source of truth: start/done rewrite only the
 * one `status = "..."` line, then quietly re-render so tasks.md stays fresh.
 * Spec root discovery walks up from cwd looking for spec/workflow.kvx — it is
 * independent of .codegraph, so `cg spec` works in any repo that has spec/.
 */
