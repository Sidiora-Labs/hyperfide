int cmd_spec(int argc, char **argv, bool json) {
    { int authority_rc = hf_client_authority_guard_args("spec", argc, argv, stderr); if (authority_rc) return authority_rc; }
    const char *sub = argc > 0 ? argv[0] : "status";
    bool check = false, force = false, repair = false, no_sync = false,
         ahead = false;
    const char *feature_ov = NULL, *root_ov = NULL;
    const char *pos[4];
    int npos = 0;
    TaskSpec ts;
    const char *agent = NULL;
    const char *host = NULL, *session = NULL, *attempt = NULL;
    long ttl = 30, fence = 0;
    memset(&ts, 0, sizeof ts);
    for (int i = 1; i < argc; i++) {
        if (strcmp(argv[i], "--check") == 0) check = true;
        else if (strcmp(argv[i], "--force") == 0) force = true;
        else if (strcmp(argv[i], "--ahead") == 0) ahead = true;
        else if (strcmp(argv[i], "--repair") == 0) repair = true;
        else if (strcmp(argv[i], "--no-sync") == 0) no_sync = true;
        else if (strcmp(argv[i], "-f") == 0 && i + 1 < argc)
            feature_ov = argv[++i];
        else if (strcmp(argv[i], "--root") == 0 && i + 1 < argc)
            root_ov = argv[++i];
        else if (strcmp(argv[i], "--title") == 0 && i + 1 < argc)
            ts.title = argv[++i];
        else if (strcmp(argv[i], "--wave") == 0 && i + 1 < argc)
            ts.wave = argv[++i];
        else if (strcmp(argv[i], "--requires") == 0 && i + 1 < argc)
            ts.requires = argv[++i];
        else if (strcmp(argv[i], "--symbols") == 0 && i + 1 < argc)
            ts.symbols = argv[++i];
        else if (strcmp(argv[i], "--touches") == 0 && i + 1 < argc)
            ts.touches = argv[++i];
        else if (strcmp(argv[i], "--verify") == 0 && i + 1 < argc)
            ts.verify = argv[++i];
        else if (strcmp(argv[i], "--section") == 0 && i + 1 < argc)
            ts.section = argv[++i];
        else if (strcmp(argv[i], "--do") == 0 && i + 1 < argc)
            ts.dos = argv[++i];
        else if (strcmp(argv[i], "--reqs") == 0 && i + 1 < argc)
            ts.reqs = argv[++i];
        else if (strcmp(argv[i], "--agent") == 0 && i + 1 < argc)
            agent = argv[++i];
        else if (strcmp(argv[i], "--host") == 0 && i + 1 < argc)
            host = argv[++i];
        else if (strcmp(argv[i], "--session") == 0 && i + 1 < argc)
            session = argv[++i];
        else if (strcmp(argv[i], "--attempt") == 0 && i + 1 < argc)
            attempt = argv[++i];
        else if (strcmp(argv[i], "--fence") == 0 && i + 1 < argc)
            fence = atol(argv[++i]);
        else if (strcmp(argv[i], "--ttl") == 0 && i + 1 < argc)
            ttl = atol(argv[++i]);
        else if (npos < 4) pos[npos++] = argv[i];
    }
    if (strcmp(sub, "new") == 0) {
        if (npos != 1) {
            fprintf(stderr, "usage: hyperfide spec new <feature>\n");
            return 1;
        }
        return spec_new_cmd(root_ov, pos[0], json);
    }

    if (strcmp(sub, "render") == 0) {
        char root[4096];
        if (root_ov) snprintf(root, sizeof root, "%s", root_ov);
        else if (spec_find_root(root, sizeof root) != 0) {
            fprintf(stderr, "hyperfide spec: no spec/workflow.kvx found here or in "
                    "any parent directory\n");
            return 1;
        }
        return json ? spec_render_json(root, check)
                    : spec_render(root, check, false);
    }

    if (strcmp(sub, "mode") == 0) {
        if (npos != 1) {
            fprintf(stderr, "usage: hyperfide spec mode <prod|standard>\n");
            return 1;
        }
        Spec s;
        memset(&s, 0, sizeof s);
        if (root_ov) snprintf(s.root, sizeof s.root, "%s", root_ov);
        else if (spec_find_root(s.root, sizeof s.root) != 0) {
            fprintf(stderr, "hyperfide spec: no spec/workflow.kvx found here or in "
                    "any parent directory\n");
            return 1;
        }
        config_workflow_path(s.root, s.wfpath, sizeof s.wfpath);
        s.wf = kvx_parse(s.wfpath);
        if (!s.wf) {
            fprintf(stderr, "hyperfide spec: cannot parse %s\n", s.wfpath);
            return 1;
        }
        int rc = spec_mode_cmd(&s, pos[0], json);
        spec_close(&s);
        return rc;
    }

    if (strcmp(sub, "status") != 0 && strcmp(sub, "next") != 0 &&
        strcmp(sub, "start") != 0 && strcmp(sub, "implemented") != 0 &&
        strcmp(sub, "done") != 0 && strcmp(sub, "mode") != 0 &&
        strcmp(sub, "trace") != 0 && strcmp(sub, "add") != 0 &&
        strcmp(sub, "docs") != 0 &&
        strcmp(sub, "lint") != 0 && strcmp(sub, "wave") != 0 &&
        strcmp(sub, "claim") != 0 && strcmp(sub, "release") != 0 &&
        strcmp(sub, "ready") != 0 && strcmp(sub, "claim-next") != 0 &&
        strcmp(sub, "heartbeat") != 0 && strcmp(sub, "reconcile") != 0) {
        fprintf(stderr, "usage: hyperfide spec [render [--check] | status | next | "
                "new <feature> | add <id> --title T [--wave N] [--requires a,b]"
                " [--symbols a,b] [--touches a,b] [--verify CMD] [--do \"a;b\"]"
                " [--reqs a,b] | lint | mode <standard|prod|parallel> | start <id> | "
                "implemented <id> | done <id> [--force] | trace [<id>] | "
                "wave | ready | claim <id> [--agent N] [--ttl M] | "
                "release <id> [--agent N] [--force] | "
                "claim-next [--agent N] [--ttl M] | heartbeat <id> "
                "[--agent N] [--attempt ID] [--fence N] [--ttl M] | "
                "reconcile [--repair] | docs [status|auto|manual|off|start|"
                "block|reset|done]] "
                "[-f <feature>]\n");
        return 1;
    }

    Spec s;
    if (spec_load(&s, root_ov, feature_ov, false) != 0) {
        spec_close(&s);
        return 1;
    }
    /* Inherited ownership is scoped to the exact feature/id. This keeps an
     * orchestrated task's environment from authorizing same-numbered tasks
     * in nested repositories or verification fixtures. Explicit CLI
     * --attempt/--fence values remain available for administrative calls. */
    const char *env_task = getenv("CG_TASK");
    bool env_matches = false;
    if (env_task && env_task[0] && npos > 0) {
        char expected[700];
        snprintf(expected, sizeof expected, "%s/%s", s.feature,
                 strcmp(sub, "docs") == 0 ? CG_DOC_TASK : pos[0]);
        env_matches = strcmp(env_task, expected) == 0;
    }
    if (env_matches && (!attempt || !attempt[0])) {
        const char *env_attempt = getenv("CG_ATTEMPT");
        if (env_attempt && env_attempt[0]) attempt = env_attempt;
    }
    if (env_matches && fence <= 0) {
        const char *env_fence = getenv("CG_FENCE");
        if (env_fence && env_fence[0]) fence = atol(env_fence);
    }
    int rc;
    if (strcmp(sub, "status") == 0) {
        rc = spec_status_cmd(&s, json);
    } else if (strcmp(sub, "add") == 0) {
        if (npos < 1) { fprintf(stderr, "usage: hyperfide spec add <id> --title T\n");
                        rc = 1; }
        else rc = spec_add_cmd(&s, pos[0], &ts, json);
    } else if (strcmp(sub, "lint") == 0) {
        rc = spec_lint_cmd(&s, json);
    } else if (strcmp(sub, "wave") == 0) {
        rc = spec_wave_cmd(&s, json);
    } else if (strcmp(sub, "claim") == 0 || strcmp(sub, "release") == 0) {
        if (npos < 1) {
            fprintf(stderr, "usage: hyperfide spec %s <id> [--agent NAME] "
                    "[--ttl MIN]\n", sub);
            rc = 1;
        } else {
            rc = spec_claim_cmd(&s, pos[0], cg_agent_name(agent),
                                host, session,
                                ttl > 0 ? ttl : 30,
                                attempt, fence,
                                strcmp(sub, "release") == 0, force, json);
        }
    } else if (strcmp(sub, "ready") == 0) {
        rc = spec_ready_cmd(&s, json);
    } else if (strcmp(sub, "claim-next") == 0) {
        rc = spec_claim_next_cmd(&s, cg_agent_name(agent), host, session,
                                 ttl > 0 ? ttl : 30, json);
    } else if (strcmp(sub, "heartbeat") == 0) {
        if (npos != 1) {
            fprintf(stderr, "usage: hyperfide spec heartbeat <id> [--agent NAME] "
                            "[--attempt ID] [--fence N] [--ttl MIN]\n");
            rc = 1;
        } else {
            rc = spec_heartbeat_cmd(&s, pos[0], cg_agent_name(agent), attempt,
                                    fence, ttl > 0 ? ttl : 30, json);
        }
    } else if (strcmp(sub, "reconcile") == 0) {
        rc = spec_reconcile_cmd(&s, repair, json);
    } else if (strcmp(sub, "docs") == 0) {
        rc = spec_docs_cmd(&s, npos >= 1 ? pos[0] : "status",
                           cg_agent_name(agent), attempt, fence, json);
    } else if (strcmp(sub, "next") == 0) {
        rc = spec_next_cmd(&s, json);
    } else if (strcmp(sub, "trace") == 0) {
        rc = spec_trace_cmd(&s, npos >= 1 ? pos[0] : NULL, !no_sync, json);
    } else if (strcmp(sub, "start") == 0) {
        if (npos < 1) { fprintf(stderr, "usage: hyperfide spec start <id>\n"); rc = 1; }
        else if (strcmp(pos[0], CG_DOC_TASK) == 0)
            rc = spec_docs_cmd(&s, "start", cg_agent_name(agent), attempt, fence, json);
        else rc = spec_start_cmd(&s, pos[0], force, ahead, json);
    } else if (strcmp(sub, "implemented") == 0) {
        if (force) {
            fprintf(stderr, "hyperfide spec implemented does not support --force\n");
            rc = 1;
        } else if (npos != 1) {
            fprintf(stderr, "usage: hyperfide spec implemented <id>\n");
            rc = 1;
        } else {
            rc = spec_implemented_cmd(&s, pos[0], cg_agent_name(agent),
                                      attempt, fence, json);
        }
    } else {
        if (npos < 1) { fprintf(stderr, "usage: hyperfide spec done <id>\n"); rc = 1; }
        else rc = spec_done_cmd(&s, pos[0], cg_agent_name(agent), attempt,
                                fence, force, json);
    }
    spec_close(&s);
    return rc;
}
