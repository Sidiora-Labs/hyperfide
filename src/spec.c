/* Scaffold a feature — and the workflow file itself when the repo has none.
 * Without this an agent can drive a plan but never create one, so the first
 * step of the lifecycle lives outside the tool. */
static int spec_new_cmd(const char *root_ov, const char *feature, bool json) {
    for (const char *p = feature; *p; p++) {
        if (!isalnum((unsigned char)*p) && *p != '_' && *p != '-') {
            fprintf(stderr, "hyperfide spec: feature names may use letters, digits, "
                    "'-' and '_' only\n");
            return 1;
        }
    }
    char root[4096];
    if (root_ov) snprintf(root, sizeof root, "%s", root_ov);
    else if (spec_find_root(root, sizeof root) != 0) {
        if (!getcwd(root, sizeof root)) return 1;   /* bootstrap a new repo */
    }

    char specdir[4600], wfpath[4700], fdir[4700], fpath[4800];
    config_spec_dir(root, specdir, sizeof specdir);
    snprintf(wfpath, sizeof wfpath, "%s/workflow.kvx", specdir);
    snprintf(fdir, sizeof fdir, "%s/%s", specdir, feature);
    snprintf(fpath, sizeof fpath, "%s/spec.kvx", fdir);

    struct stat st;
    if (stat(fpath, &st) == 0) {
        fprintf(stderr, "hyperfide spec: %s already exists\n", fpath);
        return 1;
    }
    if (mkdirs(fdir) != 0) {
        fprintf(stderr, "hyperfide spec: cannot create %s\n", fdir);
        return 1;
    }

    bool made_wf = false;
    if (stat(wfpath, &st) != 0) {
        StrBuf b; sb_init(&b);
        const char *rel = config_spec_rel(root);
        sb_printf(&b, WORKFLOW_TEMPLATE, "Spec Workflow", feature, rel, rel);
        if (write_entire_file(wfpath, b.p, b.len) != 0) {
            fprintf(stderr, "hyperfide spec: cannot write %s\n", wfpath);
            sb_free(&b);
            return 1;
        }
        sb_free(&b);
        made_wf = true;
    }

    StrBuf b; sb_init(&b);
    sb_printf(&b, FEATURE_TEMPLATE, feature, feature, feature);
    int rc = write_entire_file(fpath, b.p, b.len);
    sb_free(&b);
    if (rc != 0) {
        fprintf(stderr, "hyperfide spec: cannot write %s\n", fpath);
        return 1;
    }
    if (!made_wf) kvx_set_string(wfpath, "meta", "active_feature", feature);

    if (json) {
        StrBuf b; sb_init(&b);
        sb_puts(&b, "{\"created\":");
        sb_json_str(&b, feature);
        sb_printf(&b, ",\"workflow_created\":%s}\n",
                  made_wf ? "true" : "false");
        fputs(b.p, stdout);
        sb_free(&b);
    } else {
        printf("created %s\n", fpath);
        if (made_wf) printf("created %s\n", wfpath);
        printf("active feature: %s\n", feature);
    }
    spec_render(root, false, true);
    return 0;
}

/* Build a kvx list literal: ["a", "b"] from "a,b" */
static char *list_literal(const char *csv) {
    StrBuf b; sb_init(&b);
    sb_putc(&b, '[');
    int n = 0;
    const char *p = csv;
    while (*p) {
        while (*p == ' ' || *p == ',') p++;
        if (!*p) break;
        const char *s = p;
        while (*p && *p != ',') p++;
        const char *e = p;
        while (e > s && e[-1] == ' ') e--;
        if (e == s) continue;
        if (n++) sb_puts(&b, ", ");
        sb_putc(&b, '"');
        for (const char *c = s; c < e; c++) {
            if (*c == '"' || *c == '\\') sb_putc(&b, '\\');
            sb_putc(&b, *c);
        }
        sb_putc(&b, '"');
    }
    sb_putc(&b, ']');
    return b.p;
}

typedef struct {
    const char *title, *wave, *requires, *symbols, *touches, *verify;
    const char *section, *dos, *reqs;
} TaskSpec;

/* Add a task to the active feature. Every write goes through the surgical kvx
 * writer, so an existing file keeps its comments, ordering, and blank lines. */
static int spec_add_cmd(Spec *s, const char *id, const TaskSpec *t,
                        bool json) {
    if (!t->title) {
        fprintf(stderr, "hyperfide spec add: --title is required\n");
        return 1;
    }
    for (const char *p = id; *p; p++) {
        if (!isdigit((unsigned char)*p) && *p != '.') {
            fprintf(stderr, "hyperfide spec add: task ids are dotted numbers "
                    "(e.g. 2.1)\n");
            return 1;
        }
    }
    if (task_exists(s, id)) {
        fprintf(stderr, "hyperfide spec add: [task.%s] already exists in %s\n",
                id, s->fpath);
        return 1;
    }
    char sec[300];
    task_sec(sec, sizeof sec, id);

    if (kvx_set_string(s->fpath, sec, "title", t->title) != 0) {
        fprintf(stderr, "hyperfide spec add: cannot write %s\n", s->fpath);
        return 1;
    }
    kvx_set_string(s->fpath, sec, "status", "pending");
    if (t->section) kvx_set_string(s->fpath, sec, "section", t->section);
    /* a task with no wave is a heading, not work — default leaves to wave 0 */
    if (t->wave)   kvx_set_raw(s->fpath, sec, "wave", t->wave);
    else if (strchr(id, '.')) kvx_set_raw(s->fpath, sec, "wave", "0");
    if (t->verify) kvx_set_string(s->fpath, sec, "verify_cmd", t->verify);

    const char *lists[][2] = {
        { "requires", t->requires }, { "symbols", t->symbols },
        { "touches",  t->touches  }, { "reqs",    t->reqs    },
    };
    for (size_t i = 0; i < sizeof lists / sizeof lists[0]; i++) {
        if (!lists[i][1]) continue;
        char *lit = list_literal(lists[i][1]);
        kvx_set_raw(s->fpath, sec, lists[i][0], lit);
        free(lit);
    }
    if (t->dos) {
        int n = 0;
        const char *p = t->dos;
        while (*p) {
            while (*p == ';' || *p == ' ') p++;
            if (!*p) break;
            const char *b = p;
            while (*p && *p != ';') p++;
            const char *e = p;
            while (e > b && e[-1] == ' ') e--;
            if (e == b) continue;
            char key[16], val[1024];
            snprintf(key, sizeof key, "do_%d", ++n);
            snprintf(val, sizeof val, "%.*s", (int)(e - b), b);
            kvx_set_string(s->fpath, sec, key, val);
        }
    }
    if (json) {
        StrBuf b; sb_init(&b);
        sb_puts(&b, "{\"added\":");
        sb_json_str(&b, id);
        sb_puts(&b, ",\"title\":");
        sb_json_str(&b, t->title);
        sb_puts(&b, "}\n");
        fputs(b.p, stdout);
        sb_free(&b);
    } else {
        printf("added task %s — %s\n", id, t->title);
    }
    spec_render(s->root, false, true);
    return 0;
}

/* ---------------- lint ---------------- */

typedef struct { StrBuf b; int errors, warnings; } Lint;

static void lint_say(Lint *l, bool error, const char *id, const char *fmt, ...) {
    va_list ap;
    sb_printf(&l->b, "  %-5s %-8s ", error ? "error" : "warn", id ? id : "-");
    va_start(ap, fmt);
    char msg[1024];
    vsnprintf(msg, sizeof msg, fmt, ap);
    va_end(ap);
    sb_printf(&l->b, "%s\n", msg);
    if (error) l->errors++; else l->warnings++;
}

/* Cycle detection over `requires`, linear in tasks plus edges: an iterative
 * depth-first search with colours (0 = unvisited, 1 = on stack, 2 = done)
 * shared across every start task, so each task and edge is walked once. A
 * back edge to a task on the stack reports the cycle members from that task
 * to the top of the stack. */
typedef struct {
    int n, cap;             /* hash capacity, power of two */
    int *slot;              /* hash slot -> task index, -1 empty */
    int **adj; int *nadj;   /* resolved requires, by task index */
    char *colour;
    int *stk, *edge;        /* DFS stack: task index, next edge */
} LintCyc;

static unsigned lint_cyc_hash(const char *k) {
    unsigned h = 2166136261u;
    for (; *k; k++) h = (h ^ (unsigned char)*k) * 16777619u;
    return h;
}

static int lint_cyc_find(const Spec *s, const LintCyc *c, const char *id) {
    for (unsigned h = lint_cyc_hash(id) & (unsigned)(c->cap - 1);;
         h = (h + 1) & (unsigned)(c->cap - 1)) {
        int v = c->slot[h];
        if (v < 0) return -1;
        if (strcmp(s->ids[v], id) == 0) return v;
    }
}

static void lint_cyc_init(Spec *s, LintCyc *c) {
    c->n = s->nids;
    c->cap = 16;
    while (c->cap < 2 * c->n + 1) c->cap <<= 1;
    c->slot = xmalloc(sizeof(int) * (size_t)c->cap);
    for (int i = 0; i < c->cap; i++) c->slot[i] = -1;
    for (int i = 0; i < c->n; i++) {
        if (lint_cyc_find(s, c, s->ids[i]) >= 0) continue;
        unsigned h = lint_cyc_hash(s->ids[i]) & (unsigned)(c->cap - 1);
        while (c->slot[h] >= 0) h = (h + 1) & (unsigned)(c->cap - 1);
        c->slot[h] = i;
    }
    size_t m = c->n ? (size_t)c->n : 1;
    c->adj = xmalloc(sizeof(int *) * m);
    c->nadj = xmalloc(sizeof(int) * m);
    c->colour = xmalloc(m);
    c->stk = xmalloc(sizeof(int) * m);
    c->edge = xmalloc(sizeof(int) * m);
    for (int i = 0; i < c->n; i++) {
        char sec[300];
        task_sec(sec, sizeof sec, s->ids[i]);
        char **reqs; int nr = kvx_list(s->f, sec, "requires", &reqs);
        c->adj[i] = xmalloc(sizeof(int) * (size_t)(nr ? nr : 1));
        c->nadj[i] = 0;
        for (int j = 0; j < nr; j++) {
            int v = lint_cyc_find(s, c, reqs[j]);
            if (v >= 0) c->adj[i][c->nadj[i]++] = v;
            free(reqs[j]);
        }
        free(reqs);
        c->colour[i] = 0;
    }
}

static void lint_cyc_free(LintCyc *c) {
    if (!c->slot) return;
    for (int i = 0; i < c->n; i++) free(c->adj[i]);
    free(c->adj); free(c->nadj); free(c->colour);
    free(c->stk); free(c->edge); free(c->slot);
}

static void lint_cycle(Spec *s, const char *id, LintCyc *c, Lint *l) {
    if (!c->slot) lint_cyc_init(s, c);
    int start = lint_cyc_find(s, c, id);
    if (start < 0 || c->colour[start]) return;
    int top = 0;
    c->stk[0] = start; c->edge[0] = 0; c->colour[start] = 1;
    while (top >= 0) {
        int u = c->stk[top];
        if (c->edge[top] >= c->nadj[u]) {
            c->colour[u] = 2;
            top--;
            continue;
        }
        int v = c->adj[u][c->edge[top]++];
        if (c->colour[v] == 0) {
            top++;
            c->stk[top] = v; c->edge[top] = 0; c->colour[v] = 1;
        } else if (c->colour[v] == 1) {
            int at = top;
            while (c->stk[at] != v) at--;
            StrBuf b; sb_init(&b);
            for (int j = at; j <= top; j++)
                sb_printf(&b, "%s -> ", s->ids[c->stk[j]]);
            sb_printf(&b, "%s", s->ids[v]);
            lint_say(l, true, s->ids[v], "requires cycle: %s", b.p);
            sb_free(&b);
        }
    }
}

/* A plan that cannot be executed is worse than no plan. Lint catches the
 * failures that only surface much later: unreachable waves, requires that
 * point at nothing, tasks with no acceptance criteria, and globs that can
 * never match a real path. */
/* A blocked task names the Ask it waits on in blocked_ask (an id from
 * `hyperfide ask`); nothing else carries one. Where the project database
 * is reachable the Ask must exist and still wait. */
static void lint_blocked(Lint *l, Spec *s, const char *sec, const char *id,
                         const char *status, Cg *asks, int *opened) {
    char *ask = S(s->f, sec, "blocked_ask");
    if (!status_blocked(status)) {
        if (ask[0])
            lint_say(l, true, id, "blocked_ask = \"%s\" on a %s task; only "
                     "a blocked task waits on an Ask", ask,
                     status[0] ? status : "pending");
        free(ask);
        return;
    }
    char *end = NULL;
    long n = ask[0] ? strtol(ask, &end, 10) : 0;
    if (!ask[0]) {
        lint_say(l, true, id, "blocked without a blocked_ask naming the Ask "
                 "it waits on");
    } else if (n <= 0 || (end && *end)) {
        lint_say(l, true, id, "blocked_ask \"%s\" is not an Ask id", ask);
    } else {
        if (!*opened) *opened = memory_open_quiet(asks) ? 1 : -1;
        sqlite3_stmt *q = *opened > 0 ? cg_prep(asks, "SELECT state,"
                                       "default_policy FROM asks WHERE id=?")
                                     : NULL;
        if (q) {
            sqlite3_bind_int64(q, 1, n);
            if (sqlite3_step(q) != SQLITE_ROW)
                lint_say(l, true, id, "blocked on Ask #%ld, which does not "
                         "exist", n);
            else {
                const char *st = (const char *)sqlite3_column_text(q, 0);
                const char *pol = (const char *)sqlite3_column_text(q, 1);
                if (st && !strcmp(st, "answered"))
                    lint_say(l, true, id, "blocked on Ask #%ld, which is "
                             "answered; the task should be in_progress", n);
                else if (pol && strcmp(pol, "block") != 0)
                    lint_say(l, true, id, "blocked on Ask #%ld, which does "
                             "not block (%s)", n, pol);
            }
            sqlite3_finalize(q);
        }
    }
    free(ask);
}

static int spec_lint_cmd(Spec *s, bool json) {
    Lint l;
    memset(&l, 0, sizeof l);
    sb_init(&l.b);
    Cg asks;
    int asks_open = 0;      /* 0 untried, 1 open, -1 unavailable */
    LintCyc cyc;
    memset(&cyc, 0, sizeof cyc);

    /* every acceptance criterion id declared by [req.*] */
    char **reqsecs; int nreq = kvx_subsections(s->f, "req", &reqsecs);

    if (kvx_has(s->f, "documentation")) {
        char *mode = S(s->f, "documentation", "mode");
        char *status = S(s->f, "documentation", "status");
        if (strcmp(mode, "auto") != 0 && strcmp(mode, "manual") != 0 &&
            strcmp(mode, "off") != 0)
            lint_say(&l, true, CG_DOC_TASK, "unknown documentation mode \"%s\"",
                     mode);
        if (strcmp(status, "pending") != 0 &&
            strcmp(status, "in_progress") != 0 &&
            strcmp(status, "blocked") != 0 && strcmp(status, "done") != 0)
            lint_say(&l, true, CG_DOC_TASK,
                     "unknown documentation status \"%s\"", status);
        free(mode);
        free(status);
    }

    for (int i = 0; i < s->nids; i++) {
        const char *id = s->ids[i];
        char sec[300];
        task_sec(sec, sizeof sec, id);
        char *title = S(s->f, sec, "title");
        if (!title[0]) lint_say(&l, true, id, "task has no title");
        free(title);

        char *status = task_status(s, id);
        if (status[0] && strcmp(status, "pending") != 0 &&
            strcmp(status, "in_progress") != 0 &&
            strcmp(status, "implemented") != 0 &&
            strcmp(status, "done") != 0 && !status_superseded(status) &&
            !status_blocked(status))
            lint_say(&l, true, id, "unknown status \"%s\"", status);
        lint_blocked(&l, s, sec, id, status, &asks, &asks_open);
        if (status_superseded(status)) {
            char *why = S(s->f, sec, "superseded_reason");
            if (!why[0])
                lint_say(&l, true, id, "superseded without a "
                         "superseded_reason");
            free(why);
        }
        free(status);

        char **rq; int nr = kvx_list(s->f, sec, "requires", &rq);
        for (int j = 0; j < nr; j++) {
            if (!task_exists(s, rq[j]))
                lint_say(&l, true, id, "requires unknown task %s", rq[j]);
            else if (strcmp(rq[j], id) == 0)
                lint_say(&l, true, id, "requires itself");
            else {
                /* a superseded task never qualifies: the dependant would
                 * wait forever */
                char *rs = task_status(s, rq[j]);
                if (status_superseded(rs))
                    lint_say(&l, true, id, "requires superseded task %s; "
                             "require what superseded it", rq[j]);
                free(rs);
            }
            free(rq[j]);
        }
        free(rq);

        if (!task_is_leaf(s, id)) continue;    /* headings need nothing more */

        lint_cycle(s, id, &cyc, &l);

        char **rs; int nrs = kvx_list(s->f, sec, "reqs", &rs);
        if (nrs == 0)
            lint_say(&l, false, id, "no reqs — nothing ties this task to an "
                     "acceptance criterion");
        for (int j = 0; j < nrs; j++) {
            char want[64];
            snprintf(want, sizeof want, "%s", rs[j]);
            char *dot = strchr(want, '.');
            bool ok = false;
            if (dot) {
                *dot = 0;
                char rsec[128], ackey[64];
                snprintf(rsec, sizeof rsec, "req.%s", want);
                snprintf(ackey, sizeof ackey, "ac_%s", dot + 1);
                ok = kvx_raw(s->f, rsec, ackey) != NULL;
            }
            if (!ok) lint_say(&l, true, id, "reqs points at %s, which no "
                              "[req.*] declares", rs[j]);
            free(rs[j]);
        }
        free(rs);

        char **tp; int ntp = kvx_list(s->f, sec, "touches", &tp);
        for (int j = 0; j < ntp; j++) {
            /* a glob nothing in the repo could ever match is a dead check */
            if (!strchr(tp[j], '*')) {
                char abs[4800];
                struct stat st;
                snprintf(abs, sizeof abs, "%s/%s", s->root, tp[j]);
                if (stat(abs, &st) != 0)
                    lint_say(&l, false, id, "touches %s, which does not exist",
                             tp[j]);
            }
            free(tp[j]);
        }
        free(tp);
    }

    lint_cyc_free(&cyc);
    for (int i = 0; i < nreq; i++) free(reqsecs[i]);
    free(reqsecs);

    if (json) {
        printf("{\"errors\":%d,\"warnings\":%d,\"report\":", l.errors,
               l.warnings);
        StrBuf j; sb_init(&j);
        sb_json_str(&j, l.b.p ? l.b.p : "");
        fputs(j.p, stdout);
        sb_free(&j);
        printf("}\n");
    } else if (l.errors || l.warnings) {
        printf("lint %s (%s):\n", s->feature, s->fpath);
        fputs(l.b.p, stdout);
        printf("%d error(s), %d warning(s)\n", l.errors, l.warnings);
    } else {
        printf("lint %s: clean\n", s->feature);
    }
    sb_free(&l.b);
    if (asks_open > 0) cg_close(&asks);
    return l.errors ? 2 : 0;
}

/* Globs the in-progress task declared it would touch. The LSP needs this to
 * mark scope drift inline; returns 0 when there is no active task or it
 * declared nothing, which means "everything is in scope". */
int spec_active_touches(char ***out) {
    *out = NULL;
    Spec s;
    if (spec_load(&s, NULL, NULL, true) != 0) { spec_close(&s); return 0; }
    const char *cur = spec_current_for_agent(&s, cg_agent_name(NULL));
    if (!cur) { spec_close(&s); return 0; }
    char sec[300];
    task_sec(sec, sizeof sec, cur);
    int n = kvx_list(s.f, sec, "touches", out);
    spec_close(&s);
    return n;
}

char *spec_active_tag(void) {
    Spec s;
    char *out = NULL;
    if (spec_load(&s, NULL, NULL, true) == 0) {
        /* Parallel ownership is never inferred from somebody else's task.
         * Outside parallel mode, preserve the long-standing rule that only
         * exactly one in-progress declaration is safe to auto-tag. */
        const char *cur = spec_parallel_mode(&s)
            ? spec_agent_leased(&s, cg_agent_name(NULL))
            : spec_in_progress_count(&s) == 1 ? spec_current(&s) : NULL;
        if (cur) {
            StrBuf b; sb_init(&b);
            sb_printf(&b, "%s/%s", s.feature, cur);
            out = b.p;
        }
    }
    spec_close(&s);
    return out;
}

char *spec_task_tag(const char *requested) {
    if (!requested || !requested[0]) return NULL;
    Spec s;
    char *out = NULL;
    if (spec_load(&s, NULL, NULL, true) != 0) {
        spec_close(&s);
        return NULL;
    }
    const char *id = requested;
    const char *slash = strchr(requested, '/');
    if (slash) {
        size_t feature_len = (size_t)(slash - requested);
        if (strlen(s.feature) != feature_len ||
            strncmp(requested, s.feature, feature_len) != 0) {
            spec_close(&s);
            return NULL;
        }
        id = slash + 1;
    }
    if (task_exists(&s, id) && task_is_leaf(&s, id)) {
        char *status = task_status(&s, id);
        if (strcmp(status, "in_progress") == 0) {
            StrBuf b; sb_init(&b);
            sb_printf(&b, "%s/%s", s.feature, id);
            out = b.p;
        }
        free(status);
    }
    spec_close(&s);
    return out;
}

/* resolve "id" or "feature/id" — or, with NULL, the calling agent's current
 * task — to a malloc'd "feature/id", regardless of status. Handoff and
 * resume need to address blocked or finished work, not only started work. */
char *spec_resolve_task(const char *requested, const char *agent) {
    Spec s;
    char *out = NULL;
    if (spec_load(&s, NULL, NULL, true) != 0) {
        spec_close(&s);
        return NULL;
    }
    const char *id = NULL;
    if (requested && requested[0]) {
        id = requested;
        const char *slash = strchr(requested, '/');
        if (slash) {
            size_t fl = (size_t)(slash - requested);
            if (strlen(s.feature) != fl ||
                strncmp(requested, s.feature, fl) != 0) {
                spec_close(&s);
                return NULL;
            }
            id = slash + 1;
        }
        if (!task_exists(&s, id) || !task_is_leaf(&s, id)) id = NULL;
    } else {
        id = spec_current_for_agent(&s, agent);
    }
    if (id) {
        StrBuf b; sb_init(&b);
        sb_printf(&b, "%s/%s", s.feature, id);
        out = b.p;
    }
    spec_close(&s);
    return out;
}

/* "feature/id" names its feature; a bare id means the active one. Several
 * features run at once under one supervisor, so the feature in the tag is
 * authoritative — never the workflow's active_feature. */
static int spec_load_tag(Spec *s, const char *requested, const char **id_out) {
    const char *slash = strchr(requested, '/');
    char feature[256] = "";
    if (slash && (size_t)(slash - requested) < sizeof feature)
        snprintf(feature, sizeof feature, "%.*s", (int)(slash - requested), requested);
    *id_out = slash ? slash + 1 : requested;
    return spec_load(s, NULL, feature[0] ? feature : NULL, true);
}

/* hyperfide-v21 5.7 (req 6 ac_4): the task file is current before every
 * commit. The claim receipt — the task's latest attempt — is the authority
 * and the kvx follows it. A live running receipt on a pending declaration
 * (a merge took another branch's copy of the file) is refreshed to
 * in_progress; the task's `evidence` key is pointed at the receipt. A
 * declaration that already calls the work finished while its receipt still
 * runs, or still calls it open after the receipt completed, is a
 * disagreement: the commit refuses instead of snapshotting a lie. With no
 * claimed task or no receipt there is nothing to reconcile. Returns 0 to
 * proceed, 1 to refuse. */
int spec_commit_sync(const char *requested) {
    Spec s;
    const char *id = NULL;
    int lrc = requested && requested[0] ? spec_load_tag(&s, requested, &id)
                                        : spec_load(&s, NULL, NULL, true);
    if (lrc != 0) { spec_close(&s); return 0; }
    Cg g;
    if (!memory_open_quiet(&g)) { spec_close(&s); return 0; }
    spec_attempt_sweep(&g);

    char own[64] = "";
    if (!id) {
        const char *agent = cg_agent_name(NULL);
        sqlite3_stmt *q = cg_prep(&g,
            "SELECT task FROM attempts WHERE agent=? AND task LIKE ?||'/%' "
            "AND state='running' AND expires>strftime('%s','now') "
            "ORDER BY fence DESC LIMIT 1");
        sqlite3_bind_text(q, 1, agent ? agent : "", -1, SQLITE_TRANSIENT);
        sqlite3_bind_text(q, 2, s.feature, -1, SQLITE_TRANSIENT);
        if (sqlite3_step(q) == SQLITE_ROW) {
            const char *t = (const char *)sqlite3_column_text(q, 0);
            const char *sl = strrchr(t, '/');
            snprintf(own, sizeof own, "%s", sl ? sl + 1 : t);
            id = own;
        }
        sqlite3_finalize(q);
        if (!id && !spec_parallel_mode(&s) && spec_in_progress_count(&s) == 1)
            id = spec_current(&s);
    }
    if (!id || !task_exists(&s, id) || !task_is_leaf(&s, id)) {
        cg_close(&g); spec_close(&s); return 0;
    }

    char tag[700], attempt[80] = "", rstate[32] = "";
    snprintf(tag, sizeof tag, "%s/%s", s.feature, id);
    sqlite3_stmt *r = cg_prep(&g,
        "SELECT attempt_id,state FROM attempts WHERE task=? "
        "ORDER BY fence DESC LIMIT 1");
    sqlite3_bind_text(r, 1, tag, -1, SQLITE_TRANSIENT);
    if (sqlite3_step(r) == SQLITE_ROW) {
        snprintf(attempt, sizeof attempt, "%s",
                 (const char *)sqlite3_column_text(r, 0));
        snprintf(rstate, sizeof rstate, "%s",
                 (const char *)sqlite3_column_text(r, 1));
    }
    sqlite3_finalize(r);
    cg_close(&g);

    bool running = strcmp(rstate, "running") == 0;
    bool completed = strcmp(rstate, "completed") == 0;
    if (!running && !completed) { spec_close(&s); return 0; }

    char sec[300];
    task_sec(sec, sizeof sec, id);
    char *st = task_status(&s, id);
    bool open = strcmp(st, "in_progress") == 0 || strcmp(st, "blocked") == 0;
    bool finished = strcmp(st, "implemented") == 0 || strcmp(st, "done") == 0;
    int rc = 0;
    if (running && !open && strcmp(st, "pending") != 0) {
        fprintf(stderr, "hyperfide commit: %s says task %s is %s, but its claim "
                "receipt (attempt %.12s) is still running — finish it with "
                "`hyperfide spec implemented %s` or `hyperfide spec done %s` "
                "rather than editing the status\n", s.fpath, id, st, attempt,
                id, id);
        rc = 1;
    } else if (completed && !finished) {
        fprintf(stderr, "hyperfide commit: %s says task %s is %s, but its claim "
                "receipt (attempt %.12s) completed — the task file is behind "
                "the receipt; re-claim the task or restore its status\n",
                s.fpath, id, st, attempt);
        rc = 1;
    } else {
        bool refreshed = false;
        if (running && strcmp(st, "pending") == 0) {
            if (kvx_set_status(s.fpath, sec, "in_progress") != 0) rc = 1;
            else refreshed = true;
        }
        char want[96];
        snprintf(want, sizeof want, "attempt:%s", attempt);
        char *have = S(s.f, sec, "evidence");
        if (rc == 0 && strcmp(have, want) != 0 &&
            kvx_set_string(s.fpath, sec, "evidence", want) != 0)
            rc = 1;
        free(have);
        if (rc != 0)
            fprintf(stderr, "hyperfide commit: could not refresh [%s] in %s\n",
                    sec, s.fpath);
        else if (refreshed)
            spec_render(s.root, false, true);
    }
    free(st);
    spec_close(&s);
    return rc;
}

/* D4, called by ask.c after an Ask is raised or answered. A waiting
 * blocking Ask (open or expired) on an in_progress task blocks it with
 * blocked_ask naming the Ask. Answering the Ask a blocked task names moves
 * it to the task's next waiting blocking Ask, or returns it to in_progress.
 * Returns 1 when the task changed, 0 when the Ask has no effect on a task. */
int spec_ask_transition(Cg *cg, long ask_id) {
    sqlite3_stmt *q = cg_prep(cg, "SELECT ifnull(task,''),default_policy,"
                                  "state FROM asks WHERE id=?");
    if (!q) return 0;
    sqlite3_bind_int64(q, 1, ask_id);
    char *task = NULL, *policy = NULL, *state = NULL;
    if (sqlite3_step(q) == SQLITE_ROW) {
        task = xstrdup((const char *)sqlite3_column_text(q, 0));
        policy = xstrdup((const char *)sqlite3_column_text(q, 1));
        state = xstrdup((const char *)sqlite3_column_text(q, 2));
    }
    sqlite3_finalize(q);
    int changed = 0;
    if (!task || !task[0] || strcmp(policy, "block") != 0) goto out;
    const char *slash = strchr(task, '/');
    char feature[256] = "";
    if (slash && (size_t)(slash - task) < sizeof feature)
        snprintf(feature, sizeof feature, "%.*s", (int)(slash - task), task);
    const char *id = slash ? slash + 1 : task;
    Spec s;
    if (spec_load(&s, cg->root, feature[0] ? feature : NULL, true) != 0 ||
        !task_exists(&s, id) || !task_is_leaf(&s, id)) {
        spec_close(&s);
        goto out;
    }
    char sec[300], me[32];
    task_sec(sec, sizeof sec, id);
    snprintf(me, sizeof me, "%ld", ask_id);
    char *status = task_status(&s, id);
    char *named = S(s.f, sec, "blocked_ask");
    if (strcmp(state, "answered") != 0) {
        if (strcmp(status, "in_progress") == 0 &&
            kvx_set_string(s.fpath, sec, "blocked_ask", me) == 0 &&
            kvx_set_status(s.fpath, sec, "blocked") == 0)
            changed = 1;
    } else if (status_blocked(status) && strcmp(named, me) == 0) {
        StrBuf tag; sb_init(&tag);
        sb_printf(&tag, "%s/%s", s.feature, id);
        sqlite3_stmt *n = cg_prep(cg,
            "SELECT id FROM asks WHERE id<>? AND task IN (?,?) AND "
            "default_policy='block' AND state IN ('open','expired') "
            "ORDER BY id LIMIT 1");
        long next = 0;
        if (n) {
            sqlite3_bind_int64(n, 1, ask_id);
            sqlite3_bind_text(n, 2, id, -1, SQLITE_TRANSIENT);
            sqlite3_bind_text(n, 3, tag.p, -1, SQLITE_TRANSIENT);
            if (sqlite3_step(n) == SQLITE_ROW) next = sqlite3_column_int64(n, 0);
            sqlite3_finalize(n);
        }
        sb_free(&tag);
        char nb[32];
        snprintf(nb, sizeof nb, "%ld", next);
        if (next) changed = kvx_set_string(s.fpath, sec, "blocked_ask", nb) == 0;
        else changed = kvx_set_status(s.fpath, sec, "in_progress") == 0 &&
                       kvx_set_string(s.fpath, sec, "blocked_ask", "") == 0;
    }
    free(status); free(named);
    spec_close(&s);
out:
    free(task); free(policy); free(state);
    return changed;
}

/* json_task of a resolved "feature/id", for callers outside the engine */
char *spec_task_packet(const char *requested) {
    if (!requested || !requested[0]) return NULL;
    Spec s;
    const char *id;
    if (spec_load_tag(&s, requested, &id) != 0) {
        spec_close(&s);
        return NULL;
    }
    char *out = NULL;
    if (task_exists(&s, id)) {
        StrBuf b; sb_init(&b);
        json_task(&s, id, &b);
        out = b.p;
    }
    spec_close(&s);
    return out;
}

/* task-scoped memory retrieval for a resolved "feature/id" */
int spec_task_memories_tag(const char *requested, Memory **out) {
    *out = NULL;
    if (!requested || !requested[0]) return 0;
    Spec s;
    const char *id;
    if (spec_load_tag(&s, requested, &id) != 0) {
        spec_close(&s);
        return 0;
    }
    int n = task_exists(&s, id) ? spec_task_memories(&s, id, out) : 0;
    spec_close(&s);
    return n;
}

