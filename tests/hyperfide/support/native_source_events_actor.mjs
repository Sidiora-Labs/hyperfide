import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import fs from 'node:fs/promises';
import {createNativeAcceptanceFixture} from './native_source_acceptance_fixture.mjs';
const f=await createNativeAcceptanceFixture({actions:["source.revisions.create","source.revisions.read","source.domains.create","source.subscriptions.create","source.subscriptions.poll","source.subscriptions.ack"]});
const checks=[];
const call=(action,input)=>f.client.call(action,input);
const subscribe=input=>call('source.subscriptions.create',input);
const poll=(subscription,more={})=>call('source.subscriptions.poll',{consumer_id:subscription.consumer_id,subscription_epoch:subscription.subscription_epoch,...more});
const ack=(subscription,delivery)=>call('source.subscriptions.ack',{consumer_id:subscription.consumer_id,subscription_epoch:subscription.subscription_epoch,event_id:delivery.event_id,lease_id:delivery.lease_id});
try {
 const initial=await subscribe({consumer_id:randomUUID(),bootstrap_revision_id:f.base.revision_id,retention_max_events:2});
 const boundaryInput={consumer_id:initial.consumer_id,bootstrap_revision_id:f.base.revision_id,retention_max_events:2,expected_previous_epoch:initial.subscription_epoch};
 const boundary=await subscribe(boundaryInput);
 assert.notEqual(boundary.subscription_epoch,initial.subscription_epoch);
 assert.equal(boundary.boundary,'RESNAPSHOT');
 assert.equal((await poll(boundary)).deliveries.length,0);
 assert.deepEqual(await subscribe(boundaryInput),boundary);
 checks.push('explicit immutable resnapshot establishes one replayable new delivery boundary without a global source head');
 const one=await f.createRevision({text:'event one\n'}),two=await f.createRevision({text:'event two\n'});
 const delivered=await poll(boundary,{limit:2});
 assert.equal(delivered.deliveries.length,2);
 assert.deepEqual(new Set(delivered.deliveries.map(value=>value.payload.revision_id)),new Set([one.revision_id,two.revision_id]));
 const applied=await ack(boundary,delivered.deliveries[0]);assert.equal(applied.duplicate,false);
 await assert.rejects(f.pool.query('DELETE FROM hyperfide.source_event_inbox WHERE consumer_id=$1',[boundary.consumer_id]),error=>error.code==='23514');
 assert.equal((await ack(boundary,delivered.deliveries[0])).duplicate,true);
 const third=await f.createRevision({text:'event beyond debt\n'});
 await assert.rejects(poll(boundary),error=>error.code==='RESNAPSHOT_REQUIRED'&&error.details.reason==='EVENT_BUDGET');
 await assert.rejects(ack(boundary,delivered.deliveries[1]),error=>error.code==='RESNAPSHOT_REQUIRED');
 const debt=(await f.pool.query('SELECT retained_events,state FROM hyperfide.source_event_consumers WHERE consumer_id=$1',[boundary.consumer_id])).rows[0];
 assert.deepEqual(debt,{retained_events:2,state:'RESNAPSHOT_REQUIRED'});
 assert.equal((await f.pool.query('SELECT count(*)::int AS n FROM hyperfide.source_event_deliveries WHERE consumer_id=$1',[boundary.consumer_id])).rows[0].n,2);
 checks.push('actual committed source events stop bounded delivery debt and force explicit resnapshot while duplicate acknowledgments apply once');
 const refreshedInput={consumer_id:boundary.consumer_id,bootstrap_revision_id:third.revision_id,retention_max_events:4,expected_previous_epoch:boundary.subscription_epoch};
 const refreshed=await subscribe(refreshedInput);
 assert.equal(refreshed.retained_events,0);
 assert.equal(refreshed.bootstrap_revision_id,third.revision_id);
 assert.deepEqual(await subscribe(refreshedInput),refreshed);
 await assert.rejects(poll(boundary),error=>error.code==='STALE_SUBSCRIPTION');
 await assert.rejects(ack(boundary,delivered.deliveries[0]),error=>error.code==='STALE_SUBSCRIPTION');
 const next=await f.createRevision({text:'new boundary event\n'});
 assert.equal((await poll(refreshed)).deliveries[0].payload.revision_id,next.revision_id);
 checks.push('resnapshot fences old epochs and only the explicit new boundary receives subsequent committed source');
 const reconnect=await subscribe({consumer_id:randomUUID(),bootstrap_revision_id:next.revision_id,retention_max_events:100});
 const first=(await poll(reconnect,{limit:1,lease_ms:1000})).deliveries[0];
 await new Promise(resolve=>setTimeout(resolve,1150));
 await assert.rejects(ack(reconnect,first),error=>error.code==='STALE_LEASE');
 const again=(await poll(reconnect,{limit:1,lease_ms:1000})).deliveries[0];
 assert.equal(again.event_id,first.event_id);assert.notEqual(again.lease_id,first.lease_id);
 assert.equal((await ack(reconnect,again)).duplicate,false);
 checks.push('real elapsed lease expiry redelivers the same event under a fresh lease and rejects the abandoned acknowledgment');
 const expires=await subscribe({consumer_id:randomUUID(),bootstrap_revision_id:next.revision_id,retention_expires_at:new Date(Date.now()+2000).toISOString()});
 await new Promise(resolve=>setTimeout(resolve,2150));
 await assert.rejects(poll(expires),error=>error.code==='RESNAPSHOT_REQUIRED'&&error.details.reason==='RETENTION_EXPIRED');
 await assert.rejects(subscribe({consumer_id:randomUUID(),bootstrap_revision_id:next.revision_id,retention_max_events:100001}),error=>error.code==='LIMIT_EXCEEDED');
 await assert.rejects(subscribe({consumer_id:randomUUID(),bootstrap_revision_id:next.revision_id,retention_expires_at:new Date(Date.now()+8*86400000).toISOString()}),error=>error.code==='LIMIT_EXCEEDED');
 checks.push('real elapsed retention deadline and oversized bounds produce typed failures');
 const backfill=await subscribe({consumer_id:randomUUID(),bootstrap_revision_id:next.revision_id,retention_max_events:1});
 await assert.rejects(poll(backfill,{limit:1}),error=>error.code==='RESNAPSHOT_REQUIRED');
 assert((await f.pool.query('SELECT count(*)::int AS n FROM hyperfide.source_event_deliveries WHERE consumer_id=$1',[backfill.consumer_id])).rows[0].n<=1);
 checks.push('historical bootstrap backfill obeys the same bounded delivery budget and never silently truncates coverage');
 const receipt={status:'PASS',checks,backend_requests:f.backend.requests.length,scope:'actual authenticated HTTP, PostgreSQL, immutable source events and SigV4 objects'};
 await fs.mkdir('build/source-control/events',{recursive:true});
 await fs.writeFile('build/source-control/events/receipt.json',JSON.stringify(receipt,null,2)+'\n');
 console.log(JSON.stringify(receipt));
}finally{await f.close();}
