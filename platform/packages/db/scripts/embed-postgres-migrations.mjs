import { readMigrationFiles } from "drizzle-orm/migrator";
import { writeFileSync } from "node:fs";
const migrations = readMigrationFiles({
  migrationsFolder: new URL("../drizzle-postgres", import.meta.url).pathname,
});
writeFileSync(
  new URL("../src/postgres-migrations.generated.ts", import.meta.url),
  `// Generated by scripts/embed-postgres-migrations.mjs; do not edit.\n// Keep migration SQL available when the server is bundled into one module.\nexport const postgresMigrations = ${JSON.stringify(migrations, null, 2)};\n`,
);
